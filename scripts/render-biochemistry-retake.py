def print_pdf(html, out):
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / 'review.html'; page.write_text(html)
        subprocess.run([CHROME, '--headless=new', '--disable-gpu', '--no-pdf-header-footer', '--allow-file-access-from-files',
                        '--virtual-time-budget=20000', f'--print-to-pdf={out}', page.as_uri()], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=600)

norm = lambda s: re.sub(r'\W+', '', s).lower()

def locate(doc, texts_norm, quote, start_page=0):
    key = norm(quote)[:100]
    for i in range(start_page, len(doc)):
        if key in texts_norm[i]:
            words = quote.split()[:6]
            hits = doc[i].search_for(' '.join(words)) or doc[i].search_for(' '.join(words[:3]))
            top = hits[0].y0 / doc[i].rect.height if hits else 0.1
            return {'page': i + 1, 'top': round(top, 5)}
    raise AssertionError('Anchor text not found on one page: ' + quote[:80])

def measure(pdf_path):
    doc = fitz.open(pdf_path)
    texts = [norm(p.get_text()) for p in doc]
    sec, con, chk = {}, {}, {}
    for s in sections:
        title = norm(s['title'])
        start = next(i for i in range(2, len(doc)) if any(
            sp['size'] > 30 and norm(sp['text']) and title.startswith(norm(sp['text'])[:20])
            for b in doc[i].get_text('dict')['blocks'] if b['type'] == 0 for l in b['lines'] for sp in l['spans']) and title[:20] in texts[i])
        sec[s['id']] = {'page': start + 1, 'top': 0.07}
        image_only_ids = {f.get('concept') for f in figures if f.get('concept')}
        for c in s['concepts']:
            q = concept_quote(c, c['id'] in image_only_ids)
            con[c['id']] = {**locate(doc, texts, q, start), 'quote': q}
        for cp in s.get('checkpoints', []):
            point = {**locate(doc, texts, cp['summary'], start), 'quote': cp['summary']}
            for qid in cp['questionIds']: chk[qid] = point
    return doc, sec, con, chk

