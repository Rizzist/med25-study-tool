        out += [poly(mb, X, Y, BLUE), poly(hb(26), X, Y, INK), poly(hb(33), X, Y, CORAL, 2.4, '7 6')]
        out.append(f'<line x1="{X(0)}" y1="{Y(50)}" x2="{X(26)}" y2="{Y(50)}" stroke="{GREY}" stroke-dasharray="3 5"/><line x1="{X(26)}" y1="{Y(50)}" x2="{X(26)}" y2="{Y(0)}" stroke="{GREY}" stroke-dasharray="3 5"/>')
