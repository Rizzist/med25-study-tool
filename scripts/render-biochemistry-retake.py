# ---------------------------------------------------------------- charts (computed, not drawn by hand)
CORAL, BLUE, INK, GREY = '#e0645b', '#3b7dd8', '#2b2b2b', '#8a8a8a'

def axes(w, h, pad, xlabel, ylabel, xticks, yticks, xr, yr):
    (x0, x1), (y0, y1) = xr, yr
    X = lambda v: pad + (v - x0) / (x1 - x0) * (w - pad - 14)
    Y = lambda v: h - pad + 4 - (v - y0) / (y1 - y0) * (h - pad - 14)
    out = [f'<line x1="{X(x0)}" y1="{Y(y0)}" x2="{X(x1)}" y2="{Y(y0)}" class="ax"/>',
           f'<line x1="{X(x0)}" y1="{Y(y0)}" x2="{X(x0)}" y2="{Y(y1)}" class="ax"/>']
    for v, label in xticks:
        out.append(f'<line x1="{X(v)}" y1="{Y(y0)}" x2="{X(v)}" y2="{Y(y0)+5}" class="ax"/><text x="{X(v)}" y="{Y(y0)+19}" class="tk" text-anchor="middle">{label}</text>')
    for v, label in yticks:
        out.append(f'<line x1="{X(x0)-5}" y1="{Y(v)}" x2="{X(x0)}" y2="{Y(v)}" class="ax"/><text x="{X(x0)-9}" y="{Y(v)+5}" class="tk" text-anchor="end">{label}</text>')
    out.append(f'<text x="{(X(x0)+X(x1))/2}" y="{h-2}" class="al" text-anchor="middle">{xlabel}</text>')
    out.append(f'<text x="14" y="{(Y(y0)+Y(y1))/2}" class="al" text-anchor="middle" transform="rotate(-90 14 {(Y(y0)+Y(y1))/2})">{ylabel}</text>')
    return X, Y, out

def poly(points, X, Y, color, width=2.6, dash=None):
    d = ' '.join(f'{X(x):.1f},{Y(y):.1f}' for x, y in points)
    return f'<polyline points="{d}" fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"{f" stroke-dasharray={chr(34)}{dash}{chr(34)}" if dash else ""}/>'

def chart(kind):
    w, h, pad = 560, 330, 62
    if kind == 'titration':
        pka = 4.76
        X, Y, out = axes(w, h, pad, 'equivalents of OH⁻ added', 'pH', [(0, '0'), (.5, '0.5'), (1, '1.0')], [(2, '2'), (4, '4'), (6, '6'), (8, '8'), (10, '10')], (0, 1), (2, 10))
        pts = [(x, pka + math.log10(x / (1 - x))) for x in [i / 200 for i in range(2, 197)]]
        pts = [(x, min(max(y, 2.4), 9.6)) for x, y in pts]
        out.append(f'<rect x="{X(0)}" y="{Y(pka+1)}" width="{X(1)-X(0)}" height="{Y(pka-1)-Y(pka+1)}" fill="#3b7dd8" opacity=".10"/>')
        out.append(poly(pts, X, Y, INK))
        out.append(f'<circle cx="{X(.5)}" cy="{Y(pka)}" r="5" fill="{CORAL}"/><text x="{X(.5)+12}" y="{Y(pka)+22}" class="nt" fill="{CORAL}">pH = pKa (4.76): [HA] = [A⁻]</text>')
        out.append(f'<text x="{X(.03)}" y="{Y(pka+1)-8}" class="nt" fill="{BLUE}">buffer range: pKa ± 1</text>')
        out.append(f'<text x="{X(.62)}" y="{Y(3.1)}" class="nt">acetic acid titrated with NaOH</text>')
        cap = 'Weak-acid titration curve, computed from Henderson–Hasselbalch for acetic acid (pKa 4.76). The flat middle is where the buffer resists pH change.'
    elif kind == 'oxygen':
        X, Y, out = axes(w, h, pad, 'PO₂ (mmHg)', 'O₂ saturation (%)', [(0, '0'), (20, '20'), (40, '40'), (60, '60'), (80, '80'), (100, '100')], [(0, '0'), (50, '50'), (100, '100')], (0, 100), (0, 100))
        mb = [(p, 100 * p / (p + 2.8)) for p in [i / 2 for i in range(0, 201)]]
