def display_copy(name):
    """Print-resolution JPEG of a figure (about 220 dpi at 16 cm wide); the PNG originals are untouched."""
    from PIL import Image
    src = FIGURES / f'{name}.jpg'
    out = DISPLAY / f'{name}-{hashlib.sha256(src.read_bytes()).hexdigest()[:12]}.jpg'
    if not out.exists():
        DISPLAY.mkdir(parents=True, exist_ok=True)
        im = Image.open(src).convert('RGB')
        if im.width > 1400: im = im.resize((1400, round(im.height * 1400 / im.width)), Image.LANCZOS)
        im.save(out, 'JPEG', quality=86, optimize=True, progressive=True, subsampling=0)
    return out
